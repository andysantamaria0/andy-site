const { chromium } = require('@playwright/test');
const { createClient } = require('@supabase/supabase-js');
const fs = require('node:fs');
const assert = require('node:assert/strict');
process.loadEnvFile('.env.local');
const base = process.argv[2] || 'http://127.0.0.1:3241';
const privateInput = JSON.parse(fs.readFileSync('/private/tmp/pip-film-work/watch-provision.json', 'utf8'));
const password = privateInput.recipients.find(r => r.test).password;
const out = '/private/tmp/pip-film-work';
const service = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY, { auth: { persistSession: false, autoRefreshToken: false } });
const store = service.storage.from('private-showcases');
const read = async key => { const { data, error } = await store.download('flowers-please/' + key); if (error) throw error; return JSON.parse(await data.text()); };

(async () => {
 const browser = await chromium.launch({ channel: 'chrome', headless: true });
 const result = { base, errors: [], events: [], checks: [] };
 try {
  const activeConfig = await read('access.json');
  const context = await browser.newContext({ viewport: { width: 1440, height: 1080 } });
  const page = await context.newPage(); page.setDefaultTimeout(20000);
  page.on('pageerror', e => result.errors.push(e.message));
  let view;
  page.on('response', async response => {
   if (response.url() === base + '/api/flowers-watch/session' && response.status() === 200) view = await response.json();
   if (response.url() === base + '/api/flowers-watch/events') result.events.push(response.status());
  });
  const gate = await page.goto(base + '/flowers-please/watch');
  assert.equal(gate.status(), 200);
  assert.match(gate.headers()['cache-control'], /no-store/);
  assert.match(gate.headers()['x-robots-tag'], /noindex/);
  assert.equal(await page.locator('video').count(), 0);
  await context.addCookies([{ name: 'flowers_watch_access', value: 'tampered-token', url: base }]);
  for (const asset of ['video', 'captions', 'poster']) {
   const response = await context.request.get(base + '/api/flowers-watch/media/' + asset, { maxRedirects: 0 });
   assert.equal(response.status(), 401);
  }
  const csrf = await context.request.post(base + '/api/flowers-watch/unlock', { headers: { Origin: 'https://example.com' }, data: { password } });
  assert.equal(csrf.status(), 403);
  await page.screenshot({ path: out + '/private-watch-gate.png', fullPage: true });
  await page.getByLabel('Password', { exact: true }).fill('not-a-valid-password');
  await page.getByRole('button', { name: 'Watch the film' }).click();
  await page.getByRole('alert').filter({ hasText: 'not recognized' }).waitFor();
  await page.getByLabel('Password', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Watch the film' }).click();
  await page.getByRole('heading', { name: 'Pip for Flowers Please' }).waitFor();
  const cookie = (await context.cookies()).find(c => c.name === 'flowers_watch_access');
  assert.equal(cookie.httpOnly, true); assert.equal(cookie.sameSite, 'Strict');
  if (base.startsWith('https:')) assert.equal(cookie.secure, true);
  await page.waitForFunction(() => document.querySelector('video').readyState >= 2);
  assert.equal(await page.locator('a[download]').count(), 0);
  assert.equal(await page.locator('a[href$=".mp4"],a[href$=".vtt"],a[href$=".txt"]').count(), 0);
  assert.match(await page.locator('video').getAttribute('controlslist'), /nodownload/);
  assert.equal((await page.content()).includes(process.env.SUPABASE_SERVICE_ROLE_KEY), false);
  const videoInfo = await page.evaluate(() => { const v = document.querySelector('video'); return { width: v.videoWidth, height: v.videoHeight, duration: v.duration, captions: v.textTracks[0]?.cues?.length }; });
  assert.equal(videoInfo.width, 1920); assert.ok(Math.abs(videoInfo.duration - activeConfig.media.duration) < 0.2); assert.ok(videoInfo.captions > 50);
  await page.evaluate(async () => { const v = document.querySelector('video'); v.muted = true; await v.play(); });
  await page.waitForTimeout(3500);
  await page.getByRole('button', { name: 'Architecture', exact: true }).click();
  await page.waitForTimeout(2000);
  await page.screenshot({ path: out + '/private-watch-player.png', fullPage: true });
  await page.evaluate(() => { const v = document.querySelector('video'); v.currentTime = v.duration - 2; });
  await page.waitForFunction(() => document.querySelector('video').ended);
  await page.waitForTimeout(1800);
  assert.ok(view?.id);
  const session = await read(`sessions/${view.id}.json`);
  assert.equal(session.label, 'Internal QA'); assert.equal(session.test, true);
  const { data: events, error } = await store.list('flowers-please/events/' + view.id, { limit: 1, sortBy: { column: 'name', order: 'desc' } });
  if (error) throw error;
  const last = await read(`events/${view.id}/${events[0].name}`);
  const viewed = last.playedRanges.reduce((sum, [a, b]) => sum + b - a, 0);
  assert.ok(viewed > 4 && viewed < 25, 'Seeking must not inflate viewing coverage');
  assert.equal(last.hasPlayed, true);
  result.view = { sessionId: view.id, label: session.label, uniqueSeconds: viewed, lastEvent: last.type, activeSeconds: last.activeSeconds };
  result.video = videoInfo;
  const viewerAdmin = await context.request.get(base + '/admin/flowers-please', { maxRedirects: 0 });
  assert.ok([303, 307, 308].includes(viewerAdmin.status()));
  result.checks.push('Gate hides player', 'Media requires password', 'Cross-origin unlock rejected', 'Wrong password rejected', 'Playback and captions work', 'Download links absent', 'Seeking does not count as watching', 'Viewer cannot access activity report');
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, storageState: await context.storageState(), isMobile: true, hasTouch: true });
  const phone = await mobile.newPage(); await phone.goto(base + '/flowers-please/watch');
  await phone.getByRole('heading', { name: 'Pip for Flowers Please' }).waitFor();
  assert.equal(await phone.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await phone.screenshot({ path: out + '/private-watch-mobile.png', fullPage: true });
  await mobile.close();
  // Create an isolated session for the existing owner without sending a login email.
  const email = 'andyjsantamaria@gmail.com';
  const { data: profile, error: profileError } = await service.from('profiles').select('role').eq('email', email).maybeSingle();
  if (profileError) throw profileError;
  assert.equal(profile?.role, 'super_admin');
  const { data: link, error: linkError } = await service.auth.admin.generateLink({ type: 'magiclink', email });
  if (linkError) throw linkError;
  const anon = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY, { auth: { persistSession: false, autoRefreshToken: false } });
  const privateAttempt = await anon.storage.from('private-showcases').download('flowers-please/' + activeConfig.media.video);
  assert.ok(privateAttempt.error && !privateAttempt.data);
  const publicAttempt = await fetch(process.env.NEXT_PUBLIC_SUPABASE_URL + '/storage/v1/object/public/private-showcases/flowers-please/' + activeConfig.media.video);
  assert.ok(publicAttempt.status >= 400);
  result.checks.push('Private storage rejects anonymous and public-object access', 'Signed HttpOnly cookie', 'No service credential in rendered page');
  const { data: login, error: loginError } = await anon.auth.verifyOtp({ token_hash: link.properties.hashed_token, type: 'magiclink' });
  if (loginError) throw loginError;
  const ref = new URL(process.env.NEXT_PUBLIC_SUPABASE_URL).hostname.split('.')[0];
  const value = 'base64-' + Buffer.from(JSON.stringify(login.session)).toString('base64url');
  const owner = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const chunks = value.match(/.{1,3180}/g);
  await owner.addCookies(chunks.map((chunk, i) => ({ name: `sb-${ref}-auth-token${chunks.length > 1 ? '.' + i : ''}`, value: chunk, url: base, httpOnly: false, sameSite: 'Lax' })));
  const admin = await owner.newPage(); await admin.goto(base + '/admin/flowers-please');
  await admin.getByRole('heading', { name: 'Pip viewing activity' }).waitFor();
  await admin.getByRole('heading', { name: 'Eamon', exact: true }).waitFor();
  assert.equal(await admin.getByText('Internal QA', { exact: true }).count(), 0);
  await admin.screenshot({ path: out + '/private-watch-activity.png', fullPage: true });
  result.checks.push('Mobile layout fits', 'Owner can view report', 'Test activity excluded');
  assert.deepEqual(result.errors, []);
  assert.ok(result.events.length > 2 && result.events.every(status => status === 200));
  fs.writeFileSync(out + '/private-watch-qa.json', JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2));
 } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
